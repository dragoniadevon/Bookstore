namespace Bookstore.Api.Models.Base
{
    // Базовый класс для сущностей приложения.
    //
    // Общие свойства, которые нужны большинству сущностей,
    // выносятся сюда, чтобы не дублировать их в каждом классе.
    //
    // Например, Author и Book могут наследоваться от BaseEntity
    // и автоматически получать Id, CreatedAt и ModifiedAt.
    public class BaseEntity
    {
        // Уникальный идентификатор сущности.
        //
        // Для каждой записи в базе данных Id должен быть уникальным.
        // EF Core по соглашению распознаёт свойство Id как первичный ключ.
        public int Id { get; set; }


        // Дата и время создания сущности.
        //
        // Например, когда автор или книга были добавлены в базу данных.
        public DateTime CreatedAt { get; set; }


        // Дата и время последнего изменения сущности.
        //
        // Знак '?' означает, что значение может быть null.
        //
        // Это необходимо, потому что сразу после создания объекта
        // он ещё мог ни разу не изменяться.
        public DateTime? ModifiedAt { get; set; }
    }
}