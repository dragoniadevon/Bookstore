namespace Bookstore.Api.Models
{
    // Результат удаления записи.
    //
    // Раньше удаление возвращало bool (true/false), но у "не получилось"
    // бывает две разные причины, и клиенту нужно их различать:
    // - записи с таким Id нет            -> HTTP 404 Not Found;
    // - запись есть, но на неё ссылаются -> HTTP 409 Conflict
    //   (например, у автора есть книги, удалять его нельзя).
    public enum DeleteResult
    {
        Deleted,  // удалено
        NotFound, // записи с таким Id нет
        InUse     // запись используется другими записями
    }
}
